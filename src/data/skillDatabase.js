// Helper: get all skill names
export const getAllSkillNames = () => Object.keys(skillDatabase);

// Helper: get skills by category
export const getSkillsByCategory = (category) =>
  Object.entries(skillDatabase)
    .filter(([, meta]) => meta.category === category)
    .reduce((acc, [name, meta]) => ({ ...acc, [name]: meta }), {});

// Helper: get all categories
export const getAllCategories = () =>
  [...new Set(Object.values(skillDatabase).map((s) => s.category))];

// Helper: get prerequisites tree (recursive)
export const getPrerequisiteTree = (skillName, visited = new Set()) => {
  if (visited.has(skillName)) return [];
  visited.add(skillName);
  const skill = skillDatabase[skillName];
  if (!skill) return [];
  const prereqs = skill.prerequisites || [];
  const tree = [...prereqs];
  prereqs.forEach((p) => {
    tree.push(...getPrerequisiteTree(p, visited));
  });
  return [...new Set(tree)];
};

// Helper: calculate skill synergy score between two skills
export const getSkillSynergy = (skillA, skillB) => {
  const a = skillDatabase[skillA];
  const b = skillDatabase[skillB];
  if (!a || !b) return 0;
  let synergy = 0;
  if (a.category === b.category) synergy += 2;
  if (a.subcategory === b.subcategory) synergy += 3;
  if (a.relatedSkills.includes(skillB)) synergy += 3;
  if (b.relatedSkills.includes(skillA)) synergy += 3;
  if (a.prerequisites.includes(skillB) || b.prerequisites.includes(skillA)) synergy += 2;
  return Math.min(synergy, 10); // cap at 10
};

